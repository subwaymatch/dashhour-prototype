// Fetches a walking route from where the user stands to every branch and writes lib/routes.ts.
// Routes come from OpenStreetMap data via the OSRM foot profile at routing.openstreetmap.de.
// Run again after moving a branch or the user: node scripts/fetch-routes.mjs

import { writeFile } from "node:fs/promises";
import { BRANCHES, USER } from "../lib/data.ts";

const API = "https://routing.openstreetmap.de/routed-foot/route/v1/foot";
const TOLERANCE_M = 1.5;

/** Drops points that sit within TOLERANCE_M of the line between their neighbours. */
function simplify(points) {
  const kx = 111320 * Math.cos((USER.lat * Math.PI) / 180);
  const ky = 110574;
  const offLine = ([px, py], [ax, ay], [bx, by]) => {
    const [x, y, dx, dy] = [(px - ax) * kx, (py - ay) * ky, (bx - ax) * kx, (by - ay) * ky];
    const len = Math.hypot(dx, dy);
    return len === 0 ? Math.hypot(x, y) : Math.abs(x * dy - y * dx) / len;
  };
  const keep = new Set([0, points.length - 1]);
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let worst = -1;
    let at = -1;
    for (let i = a + 1; i < b; i++) {
      const d = offLine(points[i], points[a], points[b]);
      if (d > worst) [worst, at] = [d, i];
    }
    if (worst > TOLERANCE_M) {
      keep.add(at);
      stack.push([a, at], [at, b]);
    }
  }
  return [...keep].sort((x, y) => x - y).map((i) => points[i]);
}

const routes = {};
for (const b of BRANCHES) {
  const url = `${API}/${USER.lng},${USER.lat};${b.lng},${b.lat}?overview=full&geometries=geojson`;
  const res = await fetch(url, { headers: { "User-Agent": "dashhour-prototype (route preview)" } });
  if (!res.ok) throw new Error(`${b.id}: HTTP ${res.status}`);
  const route = (await res.json()).routes[0];
  const path = simplify(route.geometry.coordinates).map(([lng, lat]) => [Number(lng.toFixed(6)), Number(lat.toFixed(6))]);
  routes[b.id] = { metres: Math.round(route.distance), path };
  console.log(`${b.id}: ${Math.round(route.distance)} m, ${path.length} points`);
  await new Promise((r) => setTimeout(r, 1000));
}

const body = Object.entries(routes)
  .map(([id, r]) => `  "${id}": { metres: ${r.metres}, path: ${JSON.stringify(r.path)} },`)
  .join("\n");

await writeFile(
  new URL("../lib/routes.ts", import.meta.url),
  `// Generated by scripts/fetch-routes.mjs from OpenStreetMap data. Do not edit by hand.

/** Walking route from the user to each branch: length in metres and a [lng, lat] path. */
export const WALKING_ROUTES: Record<string, { metres: number; path: [number, number][] }> = {
${body}
};
`,
);
